import { BarChart3, BrainCircuit, FlaskConical, Menu, Radar, Trophy, UsersRound, X, ClipboardCheck } from 'lucide-react'
import { useState } from 'react'
import { Link, NavLink, useLocation, useNavigate } from 'react-router-dom'
import { cn, sportLabel } from '../lib/format'
import { SPORTS, Sport } from '../lib/types'
import { SportIcon } from './SportIcon'
import { DemoBadge } from './ui'

export function Logo({ className }: { className?: string }) {
  return (
    <Link to="/" className={cn('flex items-center gap-2 font-semibold tracking-tight', className)} aria-label="SPORTS AI home">
      <svg viewBox="0 0 32 32" className="h-6 w-6" aria-hidden><rect width="32" height="32" rx="7" fill="#18222B" /><path d="M5 22 L12 14 L17 18 L27 8" fill="none" stroke="rgb(var(--accent))" strokeWidth="2.6" strokeLinecap="round" strokeLinejoin="round" /><circle cx="27" cy="8" r="2.6" fill="rgb(var(--accent))" /></svg>
      <span>SPORTS<span className="text-accent">AI</span></span>
    </Link>
  )
}

export function SportSwitcher({ sport }: { sport: Sport }) {
  const nav = useNavigate()
  const loc = useLocation()
  const section = loc.pathname.split('/')[3] ?? 'match'
  return (
    <div role="tablist" aria-label="Sport" className="inline-flex rounded-md border hairline bg-ink-950 p-0.5">
      {SPORTS.map((s) => (
        <button key={s} role="tab" aria-selected={s === sport} onClick={() => nav(`/app/${s}/${section}`)}
          className={cn('flex items-center gap-1.5 rounded px-2.5 py-1 text-xs font-medium transition-colors', s === sport ? 'bg-ink-700 text-fog-100' : 'text-fog-500 hover:text-fog-100')}>
          <SportIcon sport={s} className="h-3.5 w-3.5" /> <span className="hidden sm:inline">{sportLabel[s]}</span>
        </button>
      ))}
    </div>
  )
}

const SECTIONS = [
  { to: 'match', label: 'Match Center', icon: Radar },
  { to: 'analytics', label: 'AI Analytics', icon: BarChart3 },
  { to: 'simulate', label: 'Simulation Lab', icon: FlaskConical },
  { to: 'players', label: 'Player Lab', icon: UsersRound },
]

export function AppHeader({ sport }: { sport: Sport }) {
  const [open, setOpen] = useState(false)
  const links = (
    <>
      {SECTIONS.map((s) => (
        <NavLink key={s.to} to={`/app/${sport}/${s.to}`} onClick={() => setOpen(false)}
          className={({ isActive }) => cn('flex items-center gap-1.5 rounded px-2.5 py-1.5 text-sm transition-colors', isActive ? 'bg-ink-800 text-fog-100' : 'text-fog-500 hover:text-fog-100')}>
          <s.icon className="h-4 w-4" aria-hidden /> {s.label}
        </NavLink>
      ))}
      <span className="mx-1 hidden h-5 w-px bg-ink-700 lg:block" aria-hidden />
      <NavLink to="/models" onClick={() => setOpen(false)} className={({ isActive }) => cn('flex items-center gap-1.5 rounded px-2.5 py-1.5 text-sm', isActive ? 'bg-ink-800 text-fog-100' : 'text-fog-500 hover:text-fog-100')}><BrainCircuit className="h-4 w-4" aria-hidden /> Model Insights</NavLink>
      <NavLink to="/hci" onClick={() => setOpen(false)} className={({ isActive }) => cn('flex items-center gap-1.5 rounded px-2.5 py-1.5 text-sm', isActive ? 'bg-ink-800 text-fog-100' : 'text-fog-500 hover:text-fog-100')}><ClipboardCheck className="h-4 w-4" aria-hidden /> HCI Study</NavLink>
    </>
  )
  return (
    <header className="sticky top-0 z-30 border-b hairline bg-ink-950/90 backdrop-blur">
      <div className="mx-auto flex max-w-[1500px] items-center gap-3 px-4 py-2">
        <Logo />
        <div className="ml-2"><SportSwitcher sport={sport} /></div>
        <nav aria-label="Sections" className="ml-4 hidden items-center gap-0.5 lg:flex">{links}</nav>
        <div className="ml-auto hidden sm:block"><DemoBadge /></div>
        <button className="rounded p-2 text-fog-300 hover:bg-ink-800 max-sm:ml-auto lg:hidden" aria-label={open ? 'Close menu' : 'Open menu'} aria-expanded={open} onClick={() => setOpen(!open)}>
          {open ? <X className="h-5 w-5" /> : <Menu className="h-5 w-5" />}
        </button>
      </div>
      {open && <nav aria-label="Sections" className="flex flex-col gap-0.5 border-t hairline px-3 py-2 lg:hidden">{links}<div className="mt-1 sm:hidden"><DemoBadge /></div></nav>}
    </header>
  )
}

export function Footer() {
  return (
    <footer className="mx-auto mt-10 max-w-[1500px] border-t hairline px-4 py-5 text-xs text-fog-600">
      <p className="flex items-center gap-1.5"><Trophy className="h-3.5 w-3.5" aria-hidden /> SPORTS AI is an academic prototype. All matches, players and teams are fictional and generated by reproducible simulators; predictions are model estimates, not guarantees.</p>
    </footer>
  )
}
